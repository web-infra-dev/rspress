import type { Header } from '@rspress/core';
import { useLocation, usePage } from '@rspress/core/runtime';
import { useCallback, useEffect, useState, useSyncExternalStore } from 'react';
import { processTitleElement } from './processTitleElement';

interface TocSnapshot {
  pathname: string;
  headers: Header[];
}

// Share the collected headers between the desktop and mobile outlines.
let tocSnapshot: TocSnapshot | undefined;
const listeners = new Set<() => void>();
const subscribe = (listener: () => void) => {
  listeners.add(listener);
  return () => listeners.delete(listener);
};
const getSnapshot = () => tocSnapshot;
const getServerSnapshot = () => undefined;

function setSnapshot(snapshot: TocSnapshot | undefined) {
  tocSnapshot = snapshot;
  for (const listener of listeners) {
    listener();
  }
}

function isElementOnlyVisible(element: Element): boolean {
  const style = window.getComputedStyle(element);
  return (
    style.display !== 'none' &&
    style.opacity !== '0' &&
    style.visibility !== 'hidden'
  );
}

/**
 * edge case: for users who use `display: none` to hide the element
 */
function isElementVisible(element: Element): boolean {
  let currentElement: Element | null = element;
  const rootElement = document.querySelector('.rspress-doc');
  while (currentElement) {
    if (isElementOnlyVisible(currentElement)) {
      currentElement = currentElement.parentElement;
      if (currentElement === rootElement) {
        return true;
      }
    } else {
      return false;
    }
  }
  return true;
}

/**
 * 1. in first render, use the toc generated by remark plugin
 * 2. after mounted, use the dynamically collected toc on the page
 * @internal
 */
export const useDynamicToc = (): Header[] => {
  const {
    page: { toc = [] },
  } = usePage();
  const { pathname } = useLocation();
  const snapshot = useSyncExternalStore(
    subscribe,
    getSnapshot,
    getServerSnapshot,
  );
  // An empty collection is valid; only fall back before this page is collected.
  return snapshot?.pathname === pathname ? snapshot.headers : toc;
};

function updateHeaders(target: Element, pathname: string) {
  const collectedHeaders: Header[] = [];
  const elements = target?.querySelectorAll(
    '.rspress-doc h2.rp-toc-include, h3.rp-toc-include, h4.rp-toc-include',
  );
  elements?.forEach(el => {
    if (
      !el.closest('.rspress-toc-exclude,.rp-toc-exclude') &&
      isElementVisible(el)
    ) {
      collectedHeaders.push({
        id: el.id,
        text: processTitleElement(el).innerHTML,
        depth: Number.parseInt(el.tagName[1], 10),
        charIndex: 0,
      });
    }
  });

  setSnapshot({ pathname, headers: collectedHeaders });
}

const TOC_HEADING_TAGS = new Set(['H2', 'H3', 'H4']);

/**
 * @internal
 */
export const useWatchToc = () => {
  const [innerRef, setRef] = useState<HTMLDivElement | null>(null);
  const { pathname } = useLocation();

  useEffect(() => {
    let observer: null | MutationObserver = null;

    const target = innerRef;

    if (target) {
      updateHeaders(target, pathname);
    }

    if (target && !observer) {
      observer = new MutationObserver(mutationList => {
        let needUpdate: boolean = false;
        check: for (const mutation of mutationList) {
          for (const nodes of [mutation.addedNodes, mutation.removedNodes]) {
            for (const node of nodes) {
              if (
                TOC_HEADING_TAGS.has((node as HTMLHeadingElement).tagName) ||
                node.parentElement?.closest('h2,h3,h4')
              ) {
                needUpdate = true;
                break check;
              }
              for (const child of node.childNodes) {
                if (
                  TOC_HEADING_TAGS.has((child as HTMLHeadingElement).tagName)
                ) {
                  needUpdate = true;
                  break check;
                }
              }
            }
          }
        }
        needUpdate && updateHeaders(target, pathname);
      });
      observer.observe(target, { childList: true, subtree: true });
    }
    return () => {
      observer?.disconnect();
      observer = null;
      setSnapshot(undefined);
    };
  }, [innerRef, pathname]);

  const rspressDocRef = useCallback(
    (ref: HTMLDivElement | null) => {
      setRef(ref);
    },
    [setRef],
  );

  return { rspressDocRef };
};
